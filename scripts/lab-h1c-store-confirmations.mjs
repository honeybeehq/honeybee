import assert from "node:assert/strict";
import { mkdtempSync, chmodSync } from "node:fs";
import { resolve, join } from "node:path";
import { createHash } from "node:crypto";
import { DatabaseSync } from "node:sqlite";
import { openCoreStore, replayAudit, readDeliveryConfirmations, DeliveryNotHeldError, IdempotencyConflictError, StaleGenerationError, BeeNotFoundError } from "../v2/core/src/index.ts";
const root = resolve(process.argv[2] ?? ".audit");
const dir = mkdtempSync(join(root, "h1c-lab-"));
chmodSync(dir, 0o700);
const path = join(dir, "core.sqlite");
let at = 1000;
let store = openCoreStore(path, { now: () => at++ });
const beeId = "h1c-lab";
store.createBee({ id: beeId, name: beeId, agent: "stub", substrate: "hsr", cwd: dir });
store.updateRuntimeState(beeId, 1, "running");
const host = { pid: 123, birth: "linux:123", bootId: "00000000-0000-0000-0000-000000000000" };
const prepare = (messageId, generation = store.currentRuntime(beeId).generation) => {
  const wireLine = JSON.stringify({ id: `request-${messageId}`, body: "private wire text" }) + "\n";
  return store.prepareDeliveryConfirmationIntent({ beeId, messageId, generation, wireLine, digest: createHash("sha256").update(wireLine).digest("hex"), host });
};
const parity = () => assert.deepEqual(replayAudit(store.auditRows()), store.dumpState());
const first = store.send(beeId, "original", { sender: "operator", urgency: "idle", senderKind: "human" }).message;
assert.throws(() => store.transact(() => { prepare(first.id); throw Error("crash before commit"); }));
assert.equal(store.getDeliveryConfirmationIntent(first.id), null);
const intent = prepare(first.id);
const seq = store.lastAuditSeq();
assert.deepEqual(prepare(first.id), intent);
assert.equal(store.lastAuditSeq(), seq);
assert.equal(store.getMessage(first.id).deliveryConfirmation.state, "awaiting_confirmation");
assert.equal(store.view(beeId).waitingForYou, false);
assert.throws(() => store.resolveDeliveryConfirmation({ action: "drop", beeId, messageId: first.id, generation: 1, idempotencyKey: "not-held" }), DeliveryNotHeldError);
assert.throws(() => store.prepareDeliveryConfirmationIntent({ ...intent, wireLine: "other", digest: createHash("sha256").update("other").digest("hex") }), IdempotencyConflictError);
store.updateRuntimeState(beeId, 1, "idle");
assert.equal(store.getMessage(first.id).deliveredAt, null);
store.holdDeliveryConfirmation(first.id, "old_host");
const heldSeq = store.lastAuditSeq();
store.holdDeliveryConfirmation(first.id, "old_host");
assert.equal(store.lastAuditSeq(), heldSeq);
assert.equal(store.view(beeId).deliveryConfirmations[0].reason, "old_host");
assert.equal(store.listBeeViewRows()[0].view.deliveryConfirmations[0].state, "held");
assert.equal(store.pendingMail(beeId).messages[0].deliveryConfirmation.state, "held");
assert.equal(store.mailHistory().messages[0].deliveryConfirmation.state, "held");
assert.equal(JSON.stringify(store.view(beeId)).includes("private wire text"), false);
parity();
store.close();
store = openCoreStore(path, { now: () => at++ });
assert.deepEqual(store.getDeliveryConfirmationIntent(first.id), { ...intent, state: "held", reason: "old_host" });
store.updateRuntimeState(beeId, 1, "stopped", { exitCause: "crashed" });
store.reviveBee(beeId);
store.updateRuntimeState(beeId, 2, "running");
assert.equal(store.getMessage(first.id).deliveryConfirmation.reason, "generation_changed");
assert.equal(store.markDelivered(first.id, 2).applied, false);
assert.throws(() => store.resolveDeliveryConfirmation({ action: "drop", beeId, messageId: first.id, generation: 1, idempotencyKey: "stale" }), StaleGenerationError);
parity();
const input = { action: "resend_anyway", beeId, messageId: first.id, generation: 2, idempotencyKey: "resend" };
assert.throws(() => store.transact(() => {
  store.resolveDeliveryConfirmation(input);
  throw Error("crash during explicit resend before commit");
}));
assert.ok(store.getMessage(first.id));
assert.equal(store.listMessages(beeId).length, 1);
const receipt = store.resolveDeliveryConfirmation(input);
assert.ok(receipt.replacementMessageId > first.id);
assert.equal(store.getMessage(first.id), null);
assert.equal(store.getMessage(receipt.replacementMessageId).body, first.body);
assert.equal(store.getMessage(receipt.replacementMessageId).senderKind, "human");
assert.equal(store.getMessage(receipt.replacementMessageId).urgency, "idle");
assert.deepEqual(store.resolveDeliveryConfirmation(input), { ...receipt, deduped: true });
assert.deepEqual(store.resolveDeliveryConfirmation({ ...input, idempotencyKey: "alias" }), { ...receipt, deduped: true });
assert.throws(() => store.resolveDeliveryConfirmation({ ...input, action: "drop" }), IdempotencyConflictError);
assert.throws(() => store.resolveDeliveryConfirmation({ ...input, action: "drop", idempotencyKey: "opposite" }), DeliveryNotHeldError);
parity();
const dropMessage = store.send(beeId, "drop").message;
prepare(dropMessage.id);
store.holdDeliveryConfirmation(dropMessage.id, "receipt_expired");
const drop = { action: "drop", beeId, messageId: dropMessage.id, generation: 2, idempotencyKey: "drop" };
assert.equal(store.resolveDeliveryConfirmation(drop).replacementMessageId, null);
const confirmed = store.send(beeId, "confirmed").message;
prepare(confirmed.id);
assert.throws(() => store.transact(() => {
  store.markDelivered(confirmed.id, 2);
  throw Error("crash before settlement commit");
}));
assert.equal(store.getMessage(confirmed.id).deliveredAt, null);
assert.ok(store.getDeliveryConfirmationIntent(confirmed.id));
assert.equal(store.markDelivered(confirmed.id, 2).applied, true);
assert.equal(store.getDeliveryConfirmationIntent(confirmed.id), null);
assert.equal(store.getMessage(confirmed.id).deliveryConfirmation, undefined);
const canceled = store.send(beeId, "cancel").message;
prepare(canceled.id);
store.cancelMessage(beeId, canceled.id);
assert.equal(store.getDeliveryConfirmationIntent(canceled.id), null);
const origin = { format: "honeybee.phone-origin/1", channel: "phone", issuerNodeId: "lab", assigner: "listener/1", credentialRef: "device", target: { kind: "bee", id: beeId }, contentKind: "message", assurance: "credential-possession-only", humanApproval: "not-verified", lane: "envelope-v1", parentSources: [], rootSources: [], ancestry: "complete" };
const phone = store.send(beeId, "untrusted\0<&", { phone: { origin, key: "phone" } }).message;
prepare(phone.id);
store.holdDeliveryConfirmation(phone.id, "unknown");
const phoneReceipt = store.resolveDeliveryConfirmation({ action: "resend_anyway", beeId, messageId: phone.id, generation: 2, idempotencyKey: "phone-resend" });
const copied = store.getMessage(phoneReceipt.replacementMessageId);
assert.equal(copied.phoneInput.originalContent, phone.phoneInput.originalContent);
assert.equal(copied.body, phone.body);
assert.equal(copied.phoneInput.envelope.humanApproval, "not-verified");
assert.ok(copied.phoneInput.envelope.parentSources.length);
prepare(copied.id);
store.holdDeliveryConfirmation(copied.id, "refused");
parity();
store.close();
const readonly = new DatabaseSync(path, { readOnly: true });
assert.equal(readDeliveryConfirmations(readonly, beeId, 2)[0].reason, "refused");
readonly.close();
const legacy = new DatabaseSync(":memory:");
assert.deepEqual(readDeliveryConfirmations(legacy, beeId, 2), []);
legacy.close();
store = openCoreStore(path, { now: () => at++ });
store.deleteBee(beeId);
assert.deepEqual(store.resolveDeliveryConfirmation(input), { ...receipt, deduped: true });
assert.deepEqual(store.resolveDeliveryConfirmation({ ...input, idempotencyKey: "after-delete" }), { ...receipt, deduped: true });
assert.equal(store.resolveDeliveryConfirmation(drop).deduped, true);
assert.throws(() => store.resolveDeliveryConfirmation({ action: "drop", beeId: "missing", messageId: 99999, generation: 1, idempotencyKey: "missing" }), BeeNotFoundError);
parity();
store.close();
const migrationPath = join(dir, "migration.sqlite");
const beforeMigration = openCoreStore(migrationPath);
beforeMigration.close();
const old = new DatabaseSync(migrationPath);
old.exec("DROP TABLE delivery_confirmation_intents; DROP TABLE delivery_confirmation_decisions; UPDATE meta SET value = '46' WHERE key = 'schema_version'");
old.close();
const migrated = openCoreStore(migrationPath);
assert.deepEqual(migrated.listDeliveryConfirmationIntents(), []);
migrated.close();
const migratedReadonly = new DatabaseSync(migrationPath, { readOnly: true });
assert.equal(migratedReadonly.prepare("SELECT value FROM meta WHERE key = 'schema_version'").get().value, "47");
migratedReadonly.close();
console.log(JSON.stringify({ result: "PASS", database: path, checks: ["transaction rollback", "exact binding", "semantic no-op audit", "pending is undelivered after turn end", "reopen persistence", "generation fence", "held-only decisions", "replacement row", "idempotent aliases", "conflicting keys", "drop", "atomic delivery and cancellation", "phone provenance", "read-only legacy fallback", "deletion retention", "audit replay parity", "resend and settlement rollback", "v46 to v47 migration"] }));
