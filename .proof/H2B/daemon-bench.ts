import assert from 'node:assert/strict';
import { createHash, createHmac } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { makeDaemonDir, startDaemon, waitFor } from '../../v2/daemon/tests/helpers.ts';
import { localTrustMessage, type LocalTrustChallenge } from '../../v2/daemon/src/localRpcTrust.ts';
import type { MessageRow } from '../../v2/core/src/types.ts';
import type { SpawnResult, SendRpcResult, ViewResult } from '../../v2/daemon/src/protocol.ts';
const { dir } = makeDaemonDir({rpcLocalTrust:{requireObservationCaller:true},idleWindowMs:0});
const daemon=await startDaemon(dir);
const log:unknown[]=[];
let passed=false;
try {
 const client=await daemon.client();
 const challenge=await client.request<LocalTrustChallenge>('rpc.localTrust.challenge');
 const key=readFileSync(dir+'/rpc-private/registration.key');
 const token=createHmac('sha256',key).update(localTrustMessage(challenge)).digest('hex');key.fill(0);
 await client.request('rpc.localTrust.register',{pid:process.pid,challengeId:challenge.challengeId,token});
 const {beeId}=await client.request<SpawnResult>('spawn',{name:'human-fixture',agent:'stub',cwd:dir});
 await waitFor(async()=>(await client.request<ViewResult>('view',{beeId})).view.runtimeState==='idle','idle',60000);
 await client.request('send',{beeId,body:'@hang original tool turn'});
 await waitFor(async()=>(await client.request<ViewResult>('view',{beeId})).view.working,'running');
 const background=await client.request<SendRpcResult>('send',{beeId,body:'BACKGROUND',urgency:'idle',senderKind:'automation'});
 const body='@hang HUMAN';const idempotencyKey='human-stable';
 const params={beeId,body,idempotencyKey};
 const humanChat={version:1 as const,authorityId:'fixture-workstation',admissionId:'chat-1',beeId,bodySha256:createHash('sha256').update(body).digest('hex'),idempotencyKey,humanFirst:true};
 const human=await client.request<SendRpcResult>('send',params,10000,{humanChat});
 const retry=await client.request<SendRpcResult>('send',params,10000,{humanChat});
 assert.equal(human.messageId,retry.messageId);
 const mailbox=async()=>(await client.request<{messages:MessageRow[]}>('mailbox',{beeId})).messages;
 await new Promise(r=>setTimeout(r,100));
 let rows=await mailbox(); log.push({phase:'during tool',rows});
 assert.equal(rows.find(m=>m.id===human.messageId)?.deliveredAt,null);
 await client.request('bee.interrupt',{beeId});
 await waitFor(async()=>(await mailbox()).find(m=>m.id===human.messageId)?.deliveredAt!=null,'human delivered');
 rows=await mailbox();log.push({phase:'human next turn',rows,view:await client.request('view',{beeId}),policy:await client.request('mail.humanFirst.get',{beeId})});
 assert.equal(rows.find(m=>m.id===background.messageId)?.deliveredAt,null);
 assert.equal(rows.filter(m=>m.humanChat).length,1);
 const snapshot=await client.request<{humanFirstPolicies:unknown[]}>('snapshot');assert.equal(snapshot.humanFirstPolicies.length,1);
 log.push({phase:'snapshot',policies:snapshot.humanFirstPolicies});
 client.close();passed=true;
} finally {await daemon.stop();writeFileSync(resolve('.proof/H2B/daemon-run.json'),JSON.stringify({scope:'disposable Honeybee daemon, real RPC and stub HSR; not real data',passed,log,daemonOutput:daemon.output()},null,2));}
