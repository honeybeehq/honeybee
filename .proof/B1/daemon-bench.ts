import assert from 'node:assert/strict';
import { createHash, createHmac } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, join } from 'node:path';
import { execFileSync } from 'node:child_process';
import { makeDaemonDir, startDaemon, waitFor, type DaemonHandle } from '../../v2/daemon/tests/helpers.ts';
import { RpcClient } from '../../v2/cli/src/client.ts';
import { localTrustMessage, type LocalTrustChallenge } from '../../v2/daemon/src/localRpcTrust.ts';
import type { MessageRow, MailBatch } from '../../v2/core/src/types.ts';
import type { SpawnResult, SendRpcResult, ViewResult } from '../../v2/daemon/src/protocol.ts';
const sourceRevision=execFileSync('git',['rev-parse','HEAD'],{encoding:'utf8'}).trim();
const sourceStatus=execFileSync('git',['status','--porcelain','--untracked-files=no'],{encoding:'utf8'});
assert.equal(sourceStatus,'');
const sourceStatusSha256=createHash('sha256').update(sourceStatus).digest('hex');
const benchmarkSha256=createHash('sha256').update(readFileSync(new URL(import.meta.url))).digest('hex');
const { dir } = makeDaemonDir({rpcLocalTrust:{requireObservationCaller:true},idleWindowMs:0});
let daemon: DaemonHandle = await startDaemon(dir);
const outputs: string[] = [];
const log: unknown[] = [];
let client: RpcClient | null = null;
let passed = false;
const checkpoint = (phase: string, data: unknown) => { const row = {phase, at: Date.now(), data}; log.push(row); console.log(JSON.stringify(row)); };
const register = async () => {
 const c = await daemon.client();
 const challenge = await c.request<LocalTrustChallenge>('rpc.localTrust.challenge');
 const key = readFileSync(join(dir,'rpc-private/registration.key'));
 const token = createHmac('sha256',key).update(localTrustMessage(challenge)).digest('hex'); key.fill(0);
 await c.request('rpc.localTrust.register',{pid:process.pid,challengeId:challenge.challengeId,token});
 return c;
};
try {
 client = await register();
 assert.equal(client.capabilities.includes('mail.batching.v1'),true);
 const {beeId} = await client.request<SpawnResult>('spawn',{name:'b1-runtime-fixture',agent:'stub',cwd:dir});
 const view = () => client!.request<ViewResult>('view',{beeId});
 const mailbox = async () => (await client!.request<{messages: MessageRow[]}>('mailbox',{beeId})).messages;
 const rowsSummary = async () => (await mailbox()).map(({id,automationKind,deliveredAt,deliveredGeneration,mailBatchId})=>({id,automationKind,deliveredAt,deliveredGeneration,mailBatchId}));
 await waitFor(async()=>(await view()).view.runtimeState==='idle','initial idle',60000);
 const originalRelease = join(dir,'original-release');
 const humanRelease = join(dir,'human-release');
 const repromptRelease = join(dir,'reprompt-release');
 const original = await client.request<SendRpcResult>('send',{beeId,body:`@wait-file:${originalRelease} original tool turn`});
 await waitFor(async()=>(await view()).view.working,'original tool running');
 await client.request('mail.batching.set',{beeId,enabled:true});
 await client.request('mail.humanFirst.set',{beeId,enabled:true});
 const peer = await client.request<SpawnResult>('spawn',{name:'b1-peer-fixture',agent:'inbox',cwd:dir});
 const body = `@wait-file:${humanRelease} human fixture`;
 const params = {beeId,body,idempotencyKey:'b1-human'};
 const humanChat = {version:1 as const,authorityId:'fixture-workstation',admissionId:'human-one',beeId,bodySha256:createHash('sha256').update(body).digest('hex'),idempotencyKey:params.idempotencyKey,humanFirst:true};
 const human = await client.request<SendRpcResult>('send',params,10000,{humanChat});
 const duplicate = await client.request<SendRpcResult>('send',params,10000,{humanChat});
 assert.equal(duplicate.messageId,human.messageId);
 const admitted = (await mailbox()).find(message=>message.id===human.messageId)!.humanChat!.receivedAt;
 const peers: number[] = [];
 const fullBody = '🌻'.repeat(10000)+'B1 full original';
 for(let n=0;n<12;n++) peers.push((await client.request<SendRpcResult>('send',{beeId,body:n===0?fullBody:`peer ${n}`,urgency:'now',sender:peer.beeId,idempotencyKey:`peer-${n}`})).messageId);
 const repromptParams = {beeId,body:`@wait-file:${repromptRelease} trusted reprompt`,automationKind:'tell-reprompt',automationRef:'fixture:tell',idempotencyKey:'reprompt'};
 const reprompt = await client.request<SendRpcResult>('send',repromptParams);
 const repeatedReprompt=await client.request<SendRpcResult&{deduped?:boolean}>('send',repromptParams);
 assert.equal(repeatedReprompt.messageId,reprompt.messageId);
 assert.equal(repeatedReprompt.deduped,true);
 const outsiderProof = JSON.parse(execFileSync(process.execPath,['--input-type=module','-e',`
  import { RpcClient } from ${JSON.stringify(new URL('../../v2/cli/src/client.ts',import.meta.url).href)};
  const client=await RpcClient.connect(process.argv[1]); const refused=[];
  for(const [verb,params] of [['send',{beeId:process.argv[2],body:'forged',automationKind:'blocking_decision',automationRef:'forged'}],['mail.batching.set',{beeId:process.argv[2],enabled:false}]]) {
   try {await client.request(verb,params);refused.push('ACCEPTED');} catch(error) {refused.push(error.code);}
  }
  client.close(); console.log(JSON.stringify({pid:process.pid,refused}));
 `,daemon.socketPath,beeId],{encoding:'utf8'}));
 assert.deepEqual(outsiderProof.refused,['automation_unauthorized','automation_unauthorized']);
 checkpoint('distinct unregistered PID refused',outsiderProof);
 await assert.rejects(client.request('send',{...repromptParams,automationKind:undefined,automationRef:undefined}),{code:'idempotency_conflict'});
 await new Promise(r=>setTimeout(r,200));
 assert.equal((await mailbox()).find(m=>m.id===human.messageId)?.deliveredAt,null);
 for(const id of [...peers,reprompt.messageId]) assert.equal((await mailbox()).find(m=>m.id===id)?.deliveredAt,null);
 checkpoint('tool-held human and 12 now peers and reprompt',{original:original.messageId,human:human.messageId,peers,reprompt:reprompt.messageId,rows:await rowsSummary()});
 writeFileSync(originalRelease,'release');
 await waitFor(async()=>(await mailbox()).find(m=>m.id===human.messageId)?.deliveredAt!=null,'human delivered');
 await waitFor(async()=>(await view()).view.working,'human turn active');
 for(const id of [...peers,reprompt.messageId]) assert.equal((await mailbox()).find(m=>m.id===id)?.deliveredAt,null);
 checkpoint('human runs alone',{rows:await rowsSummary()});
 writeFileSync(humanRelease,'release');
 await waitFor(async()=>(await mailbox()).find(m=>m.id===reprompt.messageId)?.deliveredAt!=null,'reprompt fresh turn');
 await waitFor(async()=>(await view()).view.working,'reprompt active');
 for(const id of peers) assert.equal((await mailbox()).find(m=>m.id===id)?.deliveredAt,null);
 checkpoint('reprompt runs alone after human',{rows:await rowsSummary()});
 writeFileSync(repromptRelease,'release');
 await waitFor(async()=>(await view()).view.runtimeState==='idle','reprompt ended');
 const beforeRestart=await view();
 client.close();client=null;
 outputs.push(daemon.output());
 await daemon.kill();
 assert.equal(daemon.proc.signalCode,'SIGKILL');
 checkpoint('fixture daemon killed before freeze',{signal:daemon.proc.signalCode});
 daemon=await startDaemon(dir);
 client=await register();
 const afterRestart=await view();
 assert.equal(afterRestart.runtime?.generation,beforeRestart.runtime?.generation);
 assert.equal(afterRestart.runtime?.pid,beforeRestart.runtime?.pid);
 for(const id of peers) assert.equal((await mailbox()).find(m=>m.id===id)?.deliveredAt,null);
 assert.equal((await client.request<{enabled:boolean}>('mail.batching.get',{beeId})).enabled,true);
 checkpoint('restart before freeze retains generation process and held peers',{generation:afterRestart.runtime?.generation,pid:afterRestart.runtime?.pid,rows:await rowsSummary()});
 while(Date.now()-admitted<120500){
  for(const id of peers) assert.equal((await mailbox()).find(m=>m.id===id)?.deliveredAt,null);
  checkpoint('human window still holds',{ageMs:Date.now()-admitted});
  await new Promise(r=>setTimeout(r,Math.min(25000,120500-(Date.now()-admitted))));
 }
 await waitFor(async()=>(await mailbox()).filter(m=>peers.includes(m.id)).every(m=>m.deliveredAt!==null),'digest released',10000);
 const rows=await mailbox();
 const settled=rows.filter(m=>peers.includes(m.id));
 const snapshot=await client.request<{mailBatches:MailBatch[]}>('snapshot');
 const batch=snapshot.mailBatches.find(b=>b.beeId===beeId&&b.memberIds.includes(peers[0]!));
 assert.ok(batch);
 assert.ok(batch.frozenAt>=admitted+120000);
 assert.ok(batch.frozenAt<=admitted+130000);
 assert.equal(batch.cutoff,peers.at(-1));
 assert.deepEqual(batch.memberIds,peers);
 assert.ok(settled.every(m=>m.deliveredAt!==null));
 assert.equal(new Set(settled.map(m=>m.deliveredGeneration)).size,1);
 assert.equal(batch.deliveredGeneration,afterRestart.runtime?.generation);
 assert.equal(settled[0]!.deliveredGeneration,afterRestart.runtime?.generation);
 assert.notEqual(batch.deliveredAt,null);
 const pageLimit=16383;
 const pages: {offset:number;nextOffset:number|null;totalBytes:number;bytes:number}[]=[];
 let offset=0;let recovered='';
 while(true){
  const page=await client.request<{body:string;offset:number;nextOffset:number|null;totalBytes:number}>('mail.batch.read',{beeId,batchId:batch.id,messageId:peers[0],offset,limit:pageLimit});
  recovered+=page.body;pages.push({offset:page.offset,nextOffset:page.nextOffset,totalBytes:page.totalBytes,bytes:Buffer.byteLength(page.body)});
  if(page.nextOffset===null)break;offset=page.nextOffset;
 }
 assert.equal(recovered,fullBody);
 assert.equal(pages.length,Math.ceil(Buffer.byteLength(fullBody)/pageLimit));
 assert.ok(pages.every(page=>page.bytes<=pageLimit));
 assert.ok(pages.every(page=>page.offset%4===0));
 assert.ok(pages.some(page=>page.nextOffset!==null&&page.bytes<pageLimit));
 await waitFor(async()=>(await view()).view.runtimeState==='idle','digest turn ended');
 const sessionLog=readFileSync((await view()).bee!.sessionLogPath!,'utf8');
 const wires=sessionLog.split('\n').filter(Boolean).map(line=>JSON.parse(line)).filter(row=>row.type==='message');
 const digests=wires.filter(row=>typeof row.body==='string'&&row.body.startsWith('Background digest\n'));
 assert.equal(digests.length,1);
 assert.equal(digests[0].id,peers[0]);
 assert.ok(wires.filter(row=>!digests.includes(row)).every(row=>!peers.includes(row.id)));
 assert.ok(Buffer.byteLength(digests[0].body)<Buffer.byteLength(fullBody));
 const envelope=JSON.parse(digests[0].body.split('\n').slice(2).join('\n'));
 assert.deepEqual(envelope.entries.map((entry:{messageId:number})=>entry.messageId),peers);
 assert.equal(envelope.entries[0].bodyRef.verb,'mail.batch.read');
 assert.ok(Buffer.byteLength(digests[0].body)<=32768);
 checkpoint('one exact 12-member digest settled with full body paging',{batch,rows:await rowsSummary(),pages,fullBodySha256:createHash('sha256').update(recovered).digest('hex'),sessionLogBytes:Buffer.byteLength(sessionLog),digestWireCount:digests.length,digestWireBytes:Buffer.byteLength(digests[0].body),wireMessageIds:wires.map(row=>row.id)});
 passed=true;
} catch(error){checkpoint('failure',{message:error instanceof Error?error.message:String(error),stack:error instanceof Error?error.stack:null});throw error;}
finally {
 client?.close();
 outputs.push(daemon.output());
 await daemon.stop();
 writeFileSync(resolve('.proof/B1/daemon-run.json'),JSON.stringify({scope:'disposable account-free daemon and stub HSR; registered RPC plus distinct PID refusal; real clock; idleWindowMs=0; restart before freeze; context/relay refusal and transaction atomicity remain unit-test scope; no live data',sourceRevision,sourceStatusSha256,benchmarkSha256,passed,log,daemonOutput:outputs},null,2));
}
