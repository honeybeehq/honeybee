import assert from "node:assert/strict";
import { mkdtempSync } from "node:fs";
import { join } from "node:path";
import { tmpdir } from "node:os";
import { openCoreStore } from "../../v2/core/src/index.ts";
import { ReadOnlyStore } from "../../v2/cli/src/readonly.ts";
import { QuotaRecovery } from "../../v2/daemon/src/quotaRecovery.ts";
const root = mkdtempSync(join(tmpdir(), "sar-e2-failed-seam-"));
const path = join(root, "core.sqlite3");
const store = openCoreStore(path, { ephemeral: true });
store.createAccount({ id: "claude-a", harness: "claude", label: "a", homePath: join(root, "a") });
const bee = store.createBee({ name: "failed", agent: "claude", substrate: "hsr", cwd: root, account: "claude-a" }).bee;
store.updateRuntimeState(bee.id, 1, "running", { pid: 1, pidStartedAt: 1 });
const original = store.send(bee.id, "owed human request").message;
store.markDelivered(original.id, 1);
store.recordQuotaEvidence({ eventId: "fixture-provider", beeId: bee.id, generation: 1,
  quota: { harness: "claude", window: "weekly", resetsAt: Date.now() + 86400000, providerCategory: "rate_limit_event" },
  turn: { messageIds: [original.id], progress: "none" } });
const row = store.listQuotaRecoveries(bee.id)[0]!;
store.claimQuotaRecovery(row.id, { targetAccount: "claude-a" });
store.bindQuotaRecovery(row.id, null);
store.updateRuntimeState(bee.id, 1, "stopped", { exitCause: "stopped_by_system" });
store.reviveBee(bee.id, { proc: { pid: 2, pidStartedAt: 2 } });
store.updateRuntimeState(bee.id, 2, "running", { synthetic: true });
const replay = store.resumeQuotaRecovery(row.id)!;
store.markDelivered(replay.continuationMessageIds[0]!, 2);
store.updateRuntimeState(bee.id, 2, "stopped", { exitCause: "crashed" });
store.setFlag(bee.id, "spawn_failed", "fixture exhausted successor budget");
const reconciler = new QuotaRecovery(store);
reconciler.reconcile();
const owed = store.getQuotaRecovery(row.id)!;
assert.equal(owed.state, "rotating");
assert.equal(owed.continuationKind, "continue");
assert.ok(store.undeliveredMessages(bee.id).some(message => owed.continuationMessageIds.includes(message.id)));
for (let poll = 0; poll < 100; poll++) reconciler.reconcile();
assert.deepEqual(store.getQuotaRecovery(row.id)?.continuationMessageIds, owed.continuationMessageIds);
assert.equal(store.view(bee.id, { readCursor: Number.MAX_SAFE_INTEGER }).waitingForYou, true);
assert.equal(store.listBeeViewRows()[0]!.view.waitingForYou, true);
store.close();
const reader = new ReadOnlyStore(path);
assert.equal(reader.view(bee.id).view.waitingForYou, true);
assert.equal(reader.list(null)[0]!.view.waitingForYou, true);
reader.close();
console.log(JSON.stringify({ phase: "failed-successor-attention", passed: true, state: owed.state, waitingForYou: true, continuationKind: owed.continuationKind, owedMessageIds: owed.continuationMessageIds, polls: 100, coreListReadonlyAgree: true }));
