import { test } from "node:test";
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { createServer } from "node:http";
import type { AddressInfo } from "node:net";
import { existsSync, mkdirSync, readFileSync, rmSync, utimesSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { claudeRefreshLockPaths, CLAUDE_REFRESH_LOCK_STALE_MS } from "../src/claudeRefreshLock.ts";
import { runV2Cli } from "../../cli/src/main.ts";
import { RpcClient } from "../../cli/src/client.ts";
import { RpcError, type AccountLeaseInstallResult, type AccountInterruptionsResult, type AuditTailResult, type MailboxResult, type SpawnResult, type ViewResult } from "../src/protocol.ts";
import { forceStopTestDaemon, makeDaemonDir, sleep, startDaemon, waitFor, type DaemonHandle } from "./helpers.ts";

test("lease enrol RPC: live unchanged process, generationless publication SIGKILL/retry, legacy first death then stamped recovery, retained receipt and profile-safe revoke", { timeout: 180_000 }, async t => {
  let validAccess = randomUUID();
  const secrets = new Set([validAccess]);
  const provider = createServer((req, res) => { res.writeHead(req.headers.authorization === `Bearer ${validAccess}` ? 200 : 401); res.end("{}"); });
  await new Promise<void>(resolve => provider.listen(0, "127.0.0.1", resolve));
  const endpoint = `http://127.0.0.1:${(provider.address() as AddressInfo).port}`;
  const root = makeDaemonDir({ idleWindowMs: 0, agents: { claude: { command: process.execPath, args: [fileURLToPath(new URL("./fixtures/auth-death-claude.mjs", import.meta.url))], adapter: "claude", env: { AUTH_DEATH_PROVIDER_URL: endpoint } } } });
  const handles: DaemonHandle[] = [];
  const clients: RpcClient[] = [];
  let db!: DaemonHandle;
  let client!: RpcClient;
  let cleanupPromise: Promise<void> | undefined;
  const cleanup = () => cleanupPromise ??= (async () => {
    for (const value of clients) value.close();
    const stopped = await Promise.allSettled(handles.map(forceStopTestDaemon));
    provider.closeAllConnections(); await new Promise<void>(resolve => provider.close(() => resolve()));
    root.cleanup();
    for (const result of stopped) if (result.status === "rejected") throw result.reason;
  })();
  t.after(cleanup); t.signal.addEventListener("abort", () => { void cleanup(); }, { once: true });
  const id = "claude-test-example.com", home = join(root.dir, "homes", id), vault = join(root.dir, "vault", "claude", id);
  const gate = join(root.dir, "enrol-gate"), marker = join(root.dir, "enrol-marker"), preload = join(root.dir, "enrol-preload.mjs");
  writeFileSync(preload, `import fs from 'node:fs'; import {syncBuiltinESMExports} from 'node:module'; const rename=fs.renameSync; fs.renameSync=(from,to)=>{ if(to===${JSON.stringify(join(vault, ".credentials.json"))} && fs.existsSync(${JSON.stringify(gate)})){fs.writeFileSync(${JSON.stringify(marker)},JSON.stringify({pid:process.pid,held:true}));process.kill(process.pid,'SIGSTOP');}return rename(from,to)};syncBuiltinESMExports();`);
  const env = (gated: boolean) => ({ HOME: join(root.dir, "empty-user-home"), HIVE_GATEWAYS_DISABLE: "1", ...(gated ? { NODE_OPTIONS: `--import ${preload}` } : {}) });
  const open = async (gated: boolean) => { db = await startDaemon(root.dir, { env: env(gated), stopTimeoutMs: 30_000 }); handles.push(db); client = await db.client(); clients.push(client); };
  const poll = <T>(fn: () => T | null | false | Promise<T | null | false>, name: string) => waitFor(fn, name, 30_000);
  const view = (beeId: string) => client.request<ViewResult>("view", { beeId });
  const interruptions = (beeId: string) => client.request<AccountInterruptionsResult>("account.interruptions", { beeId });
  const document = () => JSON.stringify({ claudeAiOauth: { accessToken: validAccess, expiresAt: Date.now() + 3_600_000, refreshToken: "" } });
  const authorityInstanceId = randomUUID();
  const params = (generation?: number, enrol = false) => ({ id, authorityInstanceId, harness: "claude", label: "test-example.com", shareId: "share-enrol-test", authorityNodeId: "authority-test", epoch: 1, ...(generation !== undefined ? { generation } : {}), ...(enrol ? { enrol: true, viaNodeId: "via-test" } : {}), expiresAt: Math.floor((Date.now() + 3_600_000) / 1000), files: [{ homeRelPath: ".credentials.json", contentB64: Buffer.from(document()).toString("base64"), mode: 0o600 }] });
  const rotate = () => { validAccess = randomUUID(); secrets.add(validAccess); };
  try {
    await open(true);
    assert.ok(client.capabilities.includes("account.lease.enrol.v1"));
    for (const path of [home, vault]) { mkdirSync(path, { recursive: true }); writeFileSync(join(path, ".credentials.json"), document()); }
    await client.request("account.add", { id, harness: "claude", label: "test-example.com", importExisting: true });
    const spawned = await client.request<SpawnResult>("spawn", { agent: "claude", name: "existing", account: id, cwd: root.dir, tags: ["autoswap=false"] });
    const before = await poll(async () => { const value = await view(spawned.beeId); return value.runtime?.state === "idle" && value.bee?.providerSessionId ? value : null; }, "existing local runtime ready");
    assert.equal(before.runtime?.credentialStamp, undefined);
    const profile = join(home, "settings.json");
    writeFileSync(profile, '{"localProfile":"preserved"}');
    const profileBefore = readFileSync(profile);
    const initial = params(undefined, true);
    const relay = await RpcClient.connect(db!.socketPath, 3000, "node_relay"); clients.push(relay);
    await assert.rejects(relay.request("account.lease.install", initial, 60_000), (error: unknown) => error instanceof RpcError && error.code === "account_lease_enrol_refused" && error.details?.reason === "local_required");
    writeFileSync(gate, "hold");
    const pending = client.request<AccountLeaseInstallResult>("account.lease.install", initial, 60_000).catch(() => null);
    await poll(() => existsSync(marker) && JSON.parse(readFileSync(marker, "utf8")).held, "enrolment stopped after durable provenance before private rename");
    await db!.kill(); await pending;
    rmSync(gate);
    const stale = new Date(Date.now() - CLAUDE_REFRESH_LOCK_STALE_MS - 1000);
    for (const path of Object.values(claudeRefreshLockPaths(home))) if (existsSync(path)) utimesSync(path, stale, stale);
    await open(false);
    const status = await client.request<{ accounts: Array<{ id: string; source: string; leasedFrom?: { materialPublished?: boolean; enrolment?: { id: string; at: number } } }> }>("account.list", {});
    const partial = status.accounts.find(row => row.id === id)!;
    assert.equal(partial.source, "leased"); assert.equal(partial.leasedFrom?.materialPublished, false);
    assert.ok(partial.leasedFrom?.enrolment);
    const completed = await client.request<AccountLeaseInstallResult>("account.lease.install", initial, 60_000);
    assert.equal(completed.account.leasedFrom?.authorityInstanceId, authorityInstanceId);
    assert.equal(completed.account.id, id); assert.equal(completed.account.leasedFrom?.materialPublished, true);
    assert.equal(completed.enrolment?.id, partial.leasedFrom?.enrolment?.id);
    assert.equal(completed.enrolment?.at, partial.leasedFrom?.enrolment?.at);
    assert.equal(completed.enrolment?.liveRuntimeCoveragePending, 1);
    const payload = join(root.dir, "enrol-payload.json");
    writeFileSync(payload, JSON.stringify(initial), { mode: 0o600 });
    const cliOut: string[] = [], cliErrors: string[] = [];
    const io = { out: (line: string) => cliOut.push(line), err: (line: string) => cliErrors.push(line) };
    assert.equal(await runV2Cli(["--data-dir", root.dir, "--json", "account", "lease", "install", "--file", payload], io), 1);
    assert.match(cliErrors.join("\n"), /explicit --enrol/);
    cliErrors.length = 0;
    assert.equal(await runV2Cli(["--data-dir", root.dir, "--json", "account", "lease", "install", "--enrol", "--file", payload], io), 0);
    const cliResult = JSON.parse(cliOut.at(-1)!) as AccountLeaseInstallResult;
    assert.deepEqual(cliResult.enrolment, completed.enrolment);
    const still = await view(spawned.beeId);
    assert.equal(still.runtime?.pid, before.runtime?.pid); assert.equal(still.runtime?.generation, before.runtime?.generation);
    assert.equal(still.bee?.providerSessionId, before.bee?.providerSessionId); assert.equal(still.bee?.cellId, before.bee?.cellId);
    assert.equal(still.runtime?.credentialStamp, undefined); assert.ok(profileBefore.equals(readFileSync(profile)), "enrolment preserves the existing profile bytes");
    rotate();
    await poll(async () => { const value = await view(spawned.beeId); return value.runtime?.state === "stopped" && (await interruptions(spawned.beeId)).interruptions.some(row => row.state === "open") ? value : null; }, "first post-enrolment auth death uses legacy interruption");
    assert.equal((await interruptions(spawned.beeId)).interruptions.at(-1)?.deathRecovery, undefined);
    const generation2 = params(2);
    const installed = await client.request<AccountLeaseInstallResult>("account.lease.install", generation2, 60_000);
    assert.deepEqual(installed.enrolment, completed.enrolment); assert.equal(installed.account.leasedFrom?.viaNodeId, "via-test");
    const admitted = await poll(async () => { const value = await view(spawned.beeId); return value.runtime?.generation === before.runtime!.generation + 1 && value.runtime.state === "idle" && value.runtime.credentialStamp ? value : null; }, "legacy continuation completed and new physical admission stamped");
    const mail = await client.request<MailboxResult>("mailbox", { beeId: spawned.beeId });
    assert.ok(mail.messages.some(message => message.sender === "hive:auth-resume" && message.deliveredAt !== null));
    assert.equal((await client.request<AuditTailResult>("audit.tail", { beeId: spawned.beeId, limit: 1000 })).rows.filter(row => row.kind === "auth_death.resumed").length, 0);
    rotate();
    await poll(async () => { const value = await view(spawned.beeId); return value.runtime?.state === "stopped" && (await interruptions(spawned.beeId)).interruptions.some(row => row.deathRecovery?.deadline != null) ? value : null; }, "subsequent stamped auth death held for newer generation");
    const generation3 = params(3);
    await client.request("account.lease.install", generation3, 60_000);
    const recovered = await poll(async () => { const value = await view(spawned.beeId); return value.runtime?.generation === admitted.runtime!.generation + 1 && value.runtime.state === "idle" ? value : null; }, "T15 once-only recovery after next publication");
    assert.equal(recovered.bee?.id, before.bee?.id); assert.equal(recovered.bee?.providerSessionId, before.bee?.providerSessionId);
    await client.request("account.lease.install", generation3, 60_000);
    await sleep(250);
    assert.equal((await view(spawned.beeId)).runtime?.generation, recovered.runtime!.generation);
    const audit = await client.request<AuditTailResult>("audit.tail", { beeId: spawned.beeId, limit: 1000 });
    assert.equal(audit.rows.filter(row => row.kind === "auth_death.resumed").length, 1);
    const evidence = JSON.stringify({ audit, completed, recovered, interruptions: await interruptions(spawned.beeId) }) + handles.map(handle => handle.output()).join("");
    assert.equal([...secrets].filter(secret => evidence.includes(secret)).length, 0, "no credential bytes in result/audit/log evidence");
    await client.request("account.lease.remove", { id });
    assert.ok(profileBefore.equals(readFileSync(profile)), "retained profile survives revocation");
    assert.equal((await view(spawned.beeId)).runtime?.generation, recovered.runtime!.generation);
    console.log("lease enrol isolated RPC: stable same-row receipt after publication SIGKILL; live process unchanged; legacy first death then stamped once-only recovery; profile retained on revoke");
  } finally { await cleanup(); }
});
