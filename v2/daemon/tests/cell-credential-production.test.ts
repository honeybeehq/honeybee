import assert from "node:assert/strict";
import { test } from "node:test";
import { mkdirSync, mkdtempSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { spawnSync } from "node:child_process";
import { openCoreStore } from "../../core/src/index.ts";
import { HiveDaemon } from "../src/daemon.ts";
import { loadNodeConfig } from "../src/config.ts";
import { AccountsService } from "../src/accountsService.ts";
import { AuthResume } from "../src/authResume.ts";
import { prepareSandboxHarnessHome } from "../../driver-cell/src/harnessHome.ts";

const material = (expiry: number, name: string, refresh: string | null = "") => JSON.stringify({OPENAI_API_KEY:null,tokens:{access_token:`e30.${Buffer.from(JSON.stringify({exp:expiry,fixture:name})).toString("base64url")}.synthetic`,refresh_token:refresh,id_token:"synthetic",account_id:"synthetic"}});

test("production lease publication, start gate and private projection run on synthetic installed material",async t=>{
  mkdirSync(resolve(".cache/t11g-trash"),{recursive:true});
  const root=mkdtempSync(resolve(".cache/hb-production-"));
  const clock=2_000_000_000_000;
  const store=openCoreStore(join(root,"core.sqlite"),{now:()=>clock,ephemeral:true});
  t.after(()=>{store.close();const r=spawnSync("trash",["--trash-dir",resolve(".cache/t11g-trash"),root],{encoding:"utf8"});assert.equal(r.status,0,r.stderr);});
  const base=loadNodeConfig(root);
  const cfg={...base,nodeKind:"satellite" as const,cellSandbox:true,accounts:{...base.accounts,vaultDir:join(root,"vault"),homesDir:join(root,"homes")}};
  cfg.agents.codex={command:process.execPath,adapter:"codex"};
  const accounts=new AccountsService({store,cfg,now:()=>clock,log:()=>{},home:root,env:{HOME:root,HIVE_NO_KEYCHAIN:"1"}});
  const daemon=new HiveDaemon(cfg,{cellCredentialNow:()=>clock});
  const internal=daemon as any;internal.store=store;internal.accounts=accounts;
  internal.authResume=new AuthResume({store,log:()=>{},now:()=>clock,accountForGeneration:(bee,generation)=>accounts.accountForGeneration(bee,generation),credentialRevision:account=>accounts.credentialRevision(account)});
  const expiry=clock/1000+3600;
  const lease=(generation:number,raw:string)=>({id:"codex-installed",harness:"codex",label:"synthetic",authorityNodeId:"fixture-authority",shareId:"fixture-share",epoch:1,generation,expiresAt:expiry,files:[{homeRelPath:"auth.json",mode:0o600,contentB64:Buffer.from(raw).toString("base64")}]});
  const firstRaw=material(expiry+3600,"first");
  const first=await internal.rpcAccountLeaseInstall(lease(1,firstRaw),{ingress:"local_unix"});
  const account=store.getAccount(first.account.id)!;assert.equal(account.source,"leased");
  const cellDir=join(root,"cell");mkdirSync(cellDir);
  const {bee}=store.createBee({name:"production",agent:"codex",substrate:"cell",account:account.id,cwd:cellDir});
  store.putCell({sourceBeeId:bee.id,originRepo:root,sha:"a".repeat(40),wrapper:"fixture",spaceName:"github-com-fixture-repo-a9015b303498-space-0012039cbb53",spaceDir:cellDir,gitCommonDirRealpath:root,objectFormat:"sha1",sandbox:true});
  assert.equal(internal.holdRuntimeStart(store.getBee(bee.id),account,1),false);
  const home=internal.resolveCellSandboxHarnessHome(bee.id);
  assert.ok(home.snapshotRoot.startsWith(join(root,"cell-access")));
  const projection=prepareSandboxHarnessHome(cellDir,"codex",home.path,home.snapshotRoot,home.liveDigests);
  internal.recordCellCredentialProjection(bee.id,1,projection.files.filter(file=>file.credentialPath).map(file=>({path:file.credentialPath,source:file.source})));
  store.mountCellCredentialProjection(bee.id,1);
  store.updateRuntimeState(bee.id,1,"running");
  assert.ok(internal.resolveCellSandboxHarnessHome(bee.id).liveDigests.length>0);
  await internal.rpcAccountLeaseInstall({...lease(2,firstRaw),expiresAt:expiry+3600},{ingress:"local_unix"});
  assert.equal(store.latestCellCredentialReplacement(bee.id,1),null);
  assert.equal(store.currentRuntime(bee.id)?.credentialStamp?.cellProjection?.expiresAt,(expiry+3600)*1000);
  await internal.rpcAccountLeaseInstall({...lease(3,material(expiry+3600,"renewed")),expiresAt:expiry+3600},{ingress:"local_unix"});
  assert.equal(store.latestCellCredentialReplacement(bee.id,1)?.args.waitForIdle,true);
  assert.equal(store.currentRuntime(bee.id)?.state,"running");
  assert.equal(store.claimNextCommand(),null);
  internal.applyAccountPolicy({beeId:bee.id,generation:1,flag:"auth_needed",action:"set",detail:"synthetic superseded 401"});
  assert.equal(store.getAccount(account.id)?.status,"ok");
  writeFileSync(join(account.homePath,"auth.json"),material(expiry,"native-again","synthetic-refresh"));
  assert.equal(internal.holdRuntimeStart(store.getBee(bee.id),store.getAccount(account.id),1),true);
  assert.ok(store.activeFlags(bee.id).some(flag=>flag.flag==="auth_needed"));
});
